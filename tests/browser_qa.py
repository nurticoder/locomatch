from playwright.sync_api import sync_playwright, expect
from pathlib import Path
from datetime import datetime,timedelta
import json,re,os
BASE=os.getenv('LOCOMATCH_QA_URL','http://127.0.0.1:5173')
OUT=Path(os.getenv('LOCOMATCH_QA_OUTPUT','test-results'));OUT.mkdir(parents=True,exist_ok=True);checks=[];errors=[]
def passed(s):checks.append(s);print('PASS:',s,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 page=browser.new_page(viewport={'width':1440,'height':1000})
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(BASE);page.wait_for_load_state('networkidle')
 if page.get_by_role('button',name='Start demo workspace',exact=True).is_visible():page.get_by_role('button',name='Start demo workspace',exact=True).click()
 page.request.post(BASE+'/api/reset')
 baseline_offers=len(page.request.get(BASE+'/api/workspace').json()['state']['bot']['outbox'])
 page.reload();page.wait_for_load_state('networkidle')
 expect(page.get_by_role('heading',name='What did you make today?',exact=True)).to_be_visible()
 page.screenshot(path=str(OUT/'locomatch-easy-upload.png'),full_page=True)
 passed('Worker homepage has three large, understandable input choices')
 page.locator('[data-easy=choose][data-method=voice]').click()
 page.get_by_role('button',name='Use a sample note',exact=True).click()
 page.get_by_role('button',name='Check the details',exact=True).click()
 expect(page.get_by_label('How many jars?',exact=True)).to_have_value('40')
 page.get_by_label('These jars are finished and ready now.',exact=True).check()
 page.get_by_role('button',name='Save for staff review',exact=True).click()
 expect(page.get_by_role('heading',name='Your stock update is saved.',exact=True)).to_be_visible()
 passed('A stock note becomes a pending batch in the shared database')
 other=browser.new_page();other.goto(BASE);other.wait_for_load_state('networkidle');other.locator('[data-nav=products]').click()
 expect(other.locator('table')).to_contain_text('Cantonese production note')
 passed('A second browser page sees the same saved stock')
 page.get_by_role('button',name='Review as sales staff',exact=True).click()
 page.get_by_label('Reviewer name',exact=True).fill('Demo reviewer')
 for box in page.locator('#verify-form input[type=checkbox]').all():box.check()
 page.get_by_role('button',name='Verify & find buyers',exact=True).click()
 expect(page.get_by_role('heading',name='2 buyers meet every rule')).to_be_visible()
 expect(page.locator('#database-state')).to_have_text('Saved online',timeout=15000)
 page.locator('[data-nav=messages]').click()
 expect(page.get_by_role('heading',name='Automatically prepared offers')).to_be_visible()
 expect(page.locator('table tbody tr')).to_have_count(baseline_offers+2)
 passed('Verifying a new batch automatically creates two eligible customer promotions')
 page.get_by_label('Test message',exact=True).fill('JOIN b1');page.get_by_role('button',name='Run simulation',exact=True).click()
 expect(page.locator('#sim-reply')).to_contain_text('Harbour Pantry')
 page.get_by_label('Test message',exact=True).fill('OFFERS');page.get_by_role('button',name='Run simulation',exact=True).click()
 expect(page.locator('#sim-reply')).to_contain_text('HK$38')
 passed('The explicitly labelled bot simulator uses verified stock from the backend')
 page.get_by_label('Test message',exact=True).fill('STOP');page.get_by_role('button',name='Run simulation',exact=True).click()
 expect(page.locator('#sim-reply')).to_contain_text('opted out')
 page.get_by_label('Test message',exact=True).fill('OFFERS');page.get_by_role('button',name='Run simulation',exact=True).click()
 expect(page.locator('#sim-reply')).to_contain_text('paused')
 passed('Opt-out takes effect in the bot and is not treated as a sent customer promotion')
 page.get_by_role('button',name='WhatsApp connection',exact=True).click()
 expect(page.get_by_label('Twilio Auth Token',exact=True)).to_have_attribute('type','password')
 page.get_by_role('button',name='Close dialog',exact=True).click()
 passed('WhatsApp setup uses a masked credential form with no secret readback')
 # Render a legible synthetic production-sheet photo for the real local OCR test.
 sheet=browser.new_page(viewport={'width':1400,'height':950})
 expiry=(datetime.now()+timedelta(days=140)).strftime('%Y-%m-%d')
 sheet.set_content('<html><body style="font:48px Arial;padding:70px;color:black;background:white"><h1 style="font-size:60px">FarmShare Demo Sheet</h1><p>Product: Orange marmalade</p><p>Quantity: 40 jars</p><p>Price: HK$38</p><p>Best before: '+expiry+'</p><p>Source: DEMO-KITCHEN-01</p></body></html>')
 sheet.screenshot(path=str(OUT/'production-sheet-demo.png'));sheet.close()
 page.locator('button[data-nav=capture]').click();page.get_by_role('button',name='Add another update',exact=True).click()
 page.locator('[data-easy=choose][data-method=photo]').click()
 page.locator('#stock-photo').set_input_files(str(OUT/'production-sheet-demo.png'))
 expect(page.locator('#stock-note')).to_have_value(re.compile('.*Orange marmalade.*',re.S),timeout=180000)
 page.get_by_role('button',name='Check the details',exact=True).click()
 expect(page.get_by_label('How many jars?',exact=True)).to_have_value('40')
 expect(page.locator('#easy-product')).to_have_value('p1')
 page.screenshot(path=str(OUT/'locomatch-photo-review.png'),full_page=True)
 passed('Real in-browser photo OCR reads the production sheet and extracts 40 jars')
 page.set_viewport_size({'width':390,'height':844})
 page.locator('button[data-nav=capture]').click()
 page.screenshot(path=str(OUT/'locomatch-easy-mobile.png'),full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 page.get_by_role('button',name='Switch to Traditional Chinese',exact=True).click()
 page.screenshot(path=str(OUT/'locomatch-easy-mobile-zh.png'),full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 passed('English and Traditional Chinese worker layouts fit a 390px phone')
 assert not errors,errors
 passed('No JavaScript errors during capture, shared saving, verification, bot simulation and OCR')
 browser.close()
OUT.joinpath('browser-v2-qa-results.json').write_text(json.dumps({'passed':checks,'runtime_errors':errors},indent=2))
